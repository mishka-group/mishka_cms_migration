defmodule MishkaCmsMigration.MixProject do
  use Mix.Project

  @version "0.0.1-alpha.1"
  @source_url "https://github.com/mishka-group/mishka_cms_migration"

  def project do
    [
      app: :mishka_cms_migration,
      name: "Mishka CMS Migration",
      version: @version,
      elixir: "~> 1.20",
      start_permanent: Mix.env() == :prod,
      deps: deps(),
      consolidate_protocols: Mix.env() != :dev,
      aliases: aliases(),
      elixirc_paths: elixirc_paths(Mix.env()),
      description: description(),
      package: package(),
      homepage_url: "https://mishka.tools/cms",
      source_url: @source_url,
      docs: [
        main: "readme",
        source_ref: "v#{@version}",
        extras: ["README.md", LICENSE: [title: "License"]],
        source_url: @source_url
      ],
      # `test/support` is compiled in the test env, where `mix ci` runs dialyzer, and it calls
      # `ExUnit`, which is not in the default PLT.
      dialyzer: [plt_add_apps: [:ex_unit]]
    ]
  end

  def cli do
    [preferred_envs: [ci: :test]]
  end

  # Run "mix help compile.app" to learn about applications.
  def application do
    [
      extra_applications: [:logger],
      mod: {MishkaCmsMigration.Application, []}
    ]
  end

  # Run "mix help deps" to learn about dependencies.
  defp deps do
    []
  end

  defp description() do
    "An extension for Mishka CMS that moves a site from WordPress, and later Joomla and other CMSs, into it, built with Elixir and Phoenix LiveView."
  end

  # Only `lib` and the files that describe the package. `priv` is generated by `mix ash.codegen` for
  # the standalone test database, including tables this extension does not own, so publishing it
  # would ship someone else's schema. `config` and `test` are absent for the same reason: they exist
  # only to run the suite on its own.
  defp package() do
    [
      licenses: ["Apache-2.0"],
      maintainers: ["Shahryar Tavakkoli"],
      files: ~w(lib .formatter.exs mix.exs LICENSE README*),
      links: %{
        "Mishka CMS" => "https://mishka.tools/cms",
        "GitHub" => @source_url,
        "Sponsor" => "https://github.com/sponsors/mishka-group",
        "Contributors" => "#{@source_url}/graphs/contributors"
      }
    ]
  end

  defp aliases() do
    [
      test: ["ash.setup --quiet", "test"],
      setup: "ash.setup",
      ci: [
        # First: after `compile` Mix has pruned its code path and the Hex archive's task is gone.
        "hex.audit",
        "compile --warnings-as-errors",
        "format --check-formatted",
        "credo --strict",
        "sobelow --config",
        "deps.audit",
        "dialyzer",
        "ex_dna --max-clones 0",
        "test"
      ]
    ]
  end

  defp elixirc_paths(:test),
    do: elixirc_paths(:dev) ++ ["test/support"]

  defp elixirc_paths(_),
    do: ["lib"]
end
